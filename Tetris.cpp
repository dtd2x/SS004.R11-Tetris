bool canMove(int dx, int dy){
    for (int i = 0; i < 4; i++ )
        for (int j = 0; j < 4; j++ )
            if (blocks[b][i][j] != ' ') {
                int xt = x + j + dx;
                int yt = y + i + dy;
                if (xt < 1 || xt >= W-1 || yt >= H-1 ) return false;
                if (board[yt][xt] != ' ') return false;
            }
    return true;
}
void block2Board(){
    for (int i = 0; i < 4; i++ )
        for (int j = 0; j < 4; j++ )
            if (blocks[b][i][j] != ' ')
                board[y+i][x+j] = blocks[b][i][j];
}
void boardDelBlock(){
    for (int i = 0; i < 4; i++ )
        for (int j = 0; j < 4; j++ )
            if (blocks[b][i][j] != ' ')
                board[y+i][x+j] = ' ';
}
void initBoard(){
    for (int i = 0 ; i < H ; i++)
        for (int j = 0 ; j < W ; j++)
            if (i == 0 || i == H-1 || j ==0 || j == W-1) board[i][j] = '#';
            else board[i][j] = ' ';
}
void draw(){
    system("cls");

    for (int i = 0; i < H; i++){
        for (int j = 0; j < W; j++){
            cout << board[i][j] << board[i][j];
        }
        cout << endl;
    }
}

int removeLine() {
    int linesRemoved = 0;

    for (int r = H - 2; r >= 1; r--) {
        bool isFull = true;

        for (int c = 1; c < W - 1; c++) {
            if (board[r][c] == ' ') {
                isFull = false;
                break;
            }
        }

        if (isFull) {
            linesRemoved++;

            for (int k = r; k > 1; k--) {
                for (int c = 1; c < W - 1; c++) {
                    board[k][c] = board[k - 1][c];
                }
            }

            for (int c = 1; c < W - 1; c++) {
                board[1][c] = ' ';
            }

            r++;
        }
    }

    return linesRemoved;
}

